describe('İşlem Geçmişi', () => {
  const open = () => renderRoutes([{ path: '/yonetim/islem-gecmisi', element: <AuditPage /> }], { path: '/yonetim/islem-gecmisi', authState: signedInState(['admin']) })
  const setup = () => userEvent.setup({ advanceTimers: vi.advanceTimersByTime })
  const row = (over: Partial<AuditRow> = {}): AuditRow => ({
    id: 9, at: '2026-11-23T11:05:00Z', actorId: 'p1', actorName: 'Admin A', table: 'payments', rowId: 'r1', action: 'update', siteId: 's1', companyId: 'c1',
    oldData: { status: 'approved', void_reason: null }, newData: { status: 'voided', void_reason: 'Yanlış tutar' }, ...over,
  })
  beforeEach(() => {
    audit.fetchAudit.mockResolvedValue({ rows: [row()], total: 1 })
  })

  it('lists who did what, with the time in Istanbul and a sentence', async () => {
    open()
    const table = await screen.findByRole('table', { name: 'İşlem geçmişi' })
    const cells = within(within(table).getAllByRole('row')[1] as HTMLElement).getAllByRole('cell')
    expect(cells.map((c) => plain(c.textContent))).toEqual(['23.11.2026 14:05', 'Admin A', 'DeğiştiÖdeme', 'Değişen: Durum, İptal nedeni', 'Ayrıntı'])
  })
  it('asks for the selected site and its company, from page 0', async () => {
    open()
    await screen.findByRole('table', { name: 'İşlem geçmişi' })
    expect(audit.fetchAudit).toHaveBeenCalledWith({ id: 's1', companyId: 'c1', name: 'Demo Sitesi' }, { table: '', action: '', actor: '', from: '', to: '' }, 0)
  })
  it('shows a person-less row as "Sistem"', async () => {
    audit.fetchAudit.mockResolvedValue({ rows: [row({ actorId: null, actorName: null })], total: 1 })
    open()
    const table = await screen.findByRole('table', { name: 'İşlem geçmişi' })
    expect(within(table).getByText('Sistem')).toBeInTheDocument()
  })
  it('opens the detail: before and after of each changed field, in words', async () => {
    const user = setup()
    open()
    await user.click(await screen.findByRole('button', { name: /Ödeme değişti.*ayrıntıyı aç/ }))
    const dialog = await screen.findByRole('dialog')
    const rows = within(dialog).getAllByRole('row')
    expect(plain(rows[1]?.textContent)).toBe('DurumOnaylıİptal edildi')
    expect(plain(rows[2]?.textContent)).toBe('İptal nedeni—Yanlış tutar')
    expect(plain(dialog.textContent)).toContain('kayıt no: r1')
    expect(plain(dialog.textContent)).toContain('Bu kayıt değiştirilemez ve silinemez')
  })
  it('opens the detail of an insert as a list of values (no "before" column)', async () => {
    audit.fetchAudit.mockResolvedValue({ rows: [row({ action: 'insert', table: 'units', oldData: null, newData: { door_no: '12', floor: 3 } })], total: 1 })
    const user = setup()
    open()
    await user.click(await screen.findByRole('button', { name: /Daire eklendi.*ayrıntıyı aç/ }))
    const dialog = await screen.findByRole('dialog')
    expect(within(dialog).queryByRole('columnheader', { name: 'Önce' })).not.toBeInTheDocument()
    expect(plain(within(dialog).getAllByRole('row')[1]?.textContent)).toBe('Kapı no12')
  })
  it('filters: nothing is asked until the person presses "Süz", then the page goes back to 0', async () => {
    const user = setup()
    open()
    await screen.findByRole('table', { name: 'İşlem geçmişi' })
    audit.fetchAudit.mockClear()
    await user.selectOptions(screen.getByLabelText('Kayıt türü'), 'units')
    await user.selectOptions(screen.getByLabelText('İşlem'), 'delete')
    await user.type(screen.getByLabelText('Kim (ad)'), 'Ayşe')
    expect(audit.fetchAudit).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Süz' }))
    await waitFor(() => expect(audit.fetchAudit).toHaveBeenCalled())
    expect(audit.fetchAudit.mock.calls.at(-1)?.[1]).toEqual({ table: 'units', action: 'delete', actor: 'Ayşe', from: '', to: '' })
    expect(audit.fetchAudit.mock.calls.at(-1)?.[2]).toBe(0)
  })
  it('clears the filters (the list is the unfiltered one again)', async () => {
    audit.fetchAudit.mockImplementation(async (_site: unknown, filters: { table: string }) => ({ rows: [row(filters.table === 'units' ? { id: 10, table: 'units', action: 'insert', oldData: null, newData: { door_no: '12' } } : {})], total: 1 }))
    const user = setup()
    open()
    expect(await screen.findByRole('button', { name: /Ödeme değişti.*ayrıntıyı aç/ })).toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Kayıt türü'), 'units')
    await user.click(screen.getByRole('button', { name: 'Süz' }))
    expect(await screen.findByRole('button', { name: /Daire eklendi.*ayrıntıyı aç/ })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Temizle' }))
    expect(await screen.findByRole('button', { name: /Ödeme değişti.*ayrıntıyı aç/ })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /Daire eklendi/ })).not.toBeInTheDocument()
    expect(screen.getByLabelText('Kayıt türü')).toHaveValue('')
  })
  it('does not accept an end date before the start date', async () => {
    const user = setup()
    open()
    await screen.findByRole('table', { name: 'İşlem geçmişi' })
    fireEvent.change(screen.getByLabelText('Başlangıç'), { target: { value: '2026-11-20' } })
    fireEvent.change(screen.getByLabelText('Bitiş'), { target: { value: '2026-11-01' } })
    expect(await screen.findByText('Başlangıç tarihi bitişten önce olmalı.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Süz' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Temizle' }))
    expect(screen.getByRole('button', { name: 'Süz' })).toBeEnabled()
  })
  it('goes back to the first page when a filter is applied', async () => {
    audit.fetchAudit.mockResolvedValue({ rows: [row()], total: 120 })
    const user = setup()
    open()
    await user.click(await screen.findByRole('button', { name: 'Sonraki' }))
    await waitFor(() => expect(audit.fetchAudit.mock.calls.at(-1)?.[2]).toBe(1))
    await user.selectOptions(screen.getByLabelText('Kayıt türü'), 'units')
    await user.click(screen.getByRole('button', { name: 'Süz' }))
    await waitFor(() => expect(audit.fetchAudit.mock.calls.at(-1)?.[1]).toMatchObject({ table: 'units' }))
    expect(audit.fetchAudit.mock.calls.at(-1)?.[2]).toBe(0)
    expect(await screen.findByText(/sayfa 1 \/ 3/)).toBeInTheDocument()
  })
  it('does not ask for a wrong range even when the form is sent without the button (Enter key)', async () => {
    open()
    await screen.findByRole('table', { name: 'İşlem geçmişi' })
    fireEvent.change(screen.getByLabelText('Başlangıç'), { target: { value: '2026-11-20' } })
    fireEvent.change(screen.getByLabelText('Bitiş'), { target: { value: '2026-11-01' } })
    audit.fetchAudit.mockClear()
    fireEvent.submit(screen.getByRole('form', { name: 'Süzgeçler' }))
    await new Promise((resolve) => setTimeout(resolve, 30))
    expect(audit.fetchAudit).not.toHaveBeenCalled()
  })
  it('pages through the log 50 at a time', async () => {
    audit.fetchAudit.mockResolvedValue({ rows: [row()], total: 120 })
    const user = setup()
    open()
    expect(await screen.findByText(/120 kayıt · sayfa 1 \/ 3/)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Önceki' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Sonraki' }))
    await waitFor(() => expect(audit.fetchAudit.mock.calls.at(-1)?.[2]).toBe(1))
    expect(await screen.findByText(/sayfa 2 \/ 3/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Sonraki' }))
    expect(await screen.findByText(/sayfa 3 \/ 3/)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Sonraki' })).toBeDisabled()
  })
  it('says so when nothing matches, and shows "try again" on an error', async () => {
    audit.fetchAudit.mockResolvedValue({ rows: [], total: 0 })
    open()
    expect(await screen.findByText('Bu süzgece uyan kayıt yok.')).toBeInTheDocument()
  })
  it('shows an error with "try again"', async () => {
    audit.fetchAudit.mockRejectedValue(new Error('boom'))
    open()
    expect(await screen.findByText(/İşlem geçmişi şu anda yüklenemedi/)).toBeInTheDocument()
  })
})

describe('Teklif Talepleri', () => {
  const open = () => renderRoutes([{ path: '/yonetim/teklif-talepleri', element: <QuoteRequestsPage /> }], { path: '/yonetim/teklif-talepleri', authState: signedInState(['admin']) })
  const setup = () => userEvent.setup({ advanceTimers: vi.advanceTimersByTime })
  const quote = (over: Partial<QuoteRow> = {}): QuoteRow => ({
    id: 'q1', name: 'Ali Veli', phone: '0532 111 22 33', email: 'ali@example.com', buildingType: 'Apartman', unitCount: 16, il: 'Kayseri', ilce: 'Melikgazi',
    message: 'Merhaba\n<script>alert(1)</script>', status: 'new', adminNote: null, createdAt: '2026-11-20T08:00:00Z', ...over,
  })
  beforeEach(() => {
    quotes.fetchQuotes.mockResolvedValue([quote(), quote({ id: 'q2', name: 'Zeynep Hanım', status: 'won', adminNote: 'Sözleşme imzalandı', phone: null })])
    quotes.updateQuoteStatus.mockResolvedValue(undefined)
    quotes.updateQuoteNote.mockResolvedValue(undefined)
    quotes.deleteQuote.mockResolvedValue(undefined)
  })

  it('lists the requests with phone and e-mail as links, the building and the place', async () => {
    open()
    const list = await screen.findByRole('list', { name: 'Teklif talepleri' })
    const first = within(list).getAllByRole('listitem')[0] as HTMLElement
    expect(within(first).getByRole('link', { name: '0532 111 22 33' })).toHaveAttribute('href', 'tel:0532 111 22 33')
    expect(within(first).getByRole('link', { name: 'ali@example.com' })).toHaveAttribute('href', 'mailto:ali@example.com')
    expect(first.textContent).toContain('Apartman · 16 daire')
    expect(first.textContent).toContain('Melikgazi, Kayseri')
  })
  it('shows the note of the admin and a dash for a missing phone', async () => {
    open()
    const list = await screen.findByRole('list', { name: 'Teklif talepleri' })
    const second = within(list).getAllByRole('listitem')[1] as HTMLElement
    expect(second.textContent).toContain('Not: Sözleşme imzalandı')
    expect(within(second).queryByRole('link', { name: /tel:/ })).not.toBeInTheDocument()
  })
  it('prints the message as plain text', async () => {
    open()
    const list = await screen.findByRole('list', { name: 'Teklif talepleri' })
    expect(list.querySelector('script')).toBeNull()
    expect(list.textContent).toContain('<script>alert(1)</script>')
  })
  it('changes the status with the box of that request', async () => {
    const user = setup()
    open()
    await user.selectOptions(await screen.findByLabelText('Ali Veli için durum'), 'offered')
    await waitFor(() => expect(quotes.updateQuoteStatus).toHaveBeenCalledWith('q1', 'offered'))
  })
  it('shows a message when the status could not be changed', async () => {
    quotes.updateQuoteStatus.mockRejectedValue({ code: '42501' })
    const user = setup()
    open()
    await user.selectOptions(await screen.findByLabelText('Ali Veli için durum'), 'offered')
    await waitFor(() => expect(toast.error).toHaveBeenCalledWith('Bu işlem için yetkiniz yok.'))
  })
  it('filters by status', async () => {
    const user = setup()
    open()
    await screen.findByRole('list', { name: 'Teklif talepleri' })
    await user.selectOptions(screen.getByLabelText('Durum'), 'won')
    const list = screen.getByRole('list', { name: 'Teklif talepleri' })
    expect(within(list).getAllByRole('listitem')).toHaveLength(1)
    expect(list.textContent).toContain('Zeynep Hanım')
    await user.selectOptions(screen.getByLabelText('Durum'), 'lost')
    expect(await screen.findByText('Bu durumda talep yok.')).toBeInTheDocument()
  })
  it('saves a note', async () => {
    const user = setup()
    open()
    await user.click((await screen.findAllByRole('button', { name: 'Mesaj ve not' }))[0] as HTMLElement)
    const dialog = await screen.findByRole('dialog')
    await user.type(within(dialog).getByLabelText(/Notunuz/), 'Yarın ararım')
    await user.click(within(dialog).getByRole('button', { name: 'Notu kaydet' }))
    await waitFor(() => expect(quotes.updateQuoteNote).toHaveBeenCalledWith('q1', 'Yarın ararım'))
  })
  it('highlights only the new requests', async () => {
    open()
    await screen.findByText('Ali Veli')
    const badges = Array.from(document.querySelectorAll('[data-slot="badge"]'))
    const fresh = badges.find((b) => b.textContent === 'Yeni')
    const won = badges.find((b) => b.textContent === 'Kazanıldı')
    expect(fresh?.className).toContain('bg-primary')
    expect(won?.className).not.toContain('bg-primary')
  })
  it('loads the list again after a delete and after a note', async () => {
    const user = setup()
    open()
    await user.click((await screen.findAllByRole('button', { name: 'Mesaj ve not' }))[0] as HTMLElement)
    const noteDialog = await screen.findByRole('dialog')
    await user.type(within(noteDialog).getByLabelText(/Notunuz/), 'Arandı')
    let before = quotes.fetchQuotes.mock.calls.length
    await user.click(within(noteDialog).getByRole('button', { name: 'Notu kaydet' }))
    await waitFor(() => expect(quotes.updateQuoteNote).toHaveBeenCalled())
    await waitFor(() => expect(quotes.fetchQuotes.mock.calls.length).toBeGreaterThan(before))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    await user.click(await screen.findByRole('button', { name: 'Ali Veli talebini sil' }))
    before = quotes.fetchQuotes.mock.calls.length
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Sil' }))
    await waitFor(() => expect(quotes.deleteQuote).toHaveBeenCalledWith('q1'))
    await waitFor(() => expect(quotes.fetchQuotes.mock.calls.length).toBeGreaterThan(before))
  })
  it('asks before deleting, then deletes', async () => {
    const user = setup()
    open()
    await user.click(await screen.findByRole('button', { name: 'Ali Veli talebini sil' }))
    expect(quotes.deleteQuote).not.toHaveBeenCalled()
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Sil' }))
    await waitFor(() => expect(quotes.deleteQuote).toHaveBeenCalledWith('q1'))
  })
  it('says so when there is nothing yet, and shows "try again" on an error', async () => {
    quotes.fetchQuotes.mockResolvedValue([])
    open()
    expect(await screen.findByText('Henüz teklif talebi gelmedi.')).toBeInTheDocument()
  })
  it('shows an error with "try again"', async () => {
    quotes.fetchQuotes.mockRejectedValue(new Error('boom'))
    open()
    expect(await screen.findByText(/Teklif talepleri şu anda yüklenemedi/)).toBeInTheDocument()
  })
})
